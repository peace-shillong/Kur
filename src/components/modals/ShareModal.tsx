import React, { useRef, useEffect, useState } from 'react';
import { useClan } from '../../context/ClanContext';
import { useLanguage } from '../../context/LanguageContext';
import { X, Image, FileText, Check, Download, Printer } from 'lucide-react';

interface ShareModalProps {
  isOpen: boolean;
  onClose: () => void;
  canvasRef?: React.RefObject<HTMLCanvasElement | null>;
}

export const ShareModal: React.FC<ShareModalProps> = ({ isOpen, onClose, canvasRef }) => {
  const { query, viewMode, graphData } = useClan();
  const { language } = useLanguage();
  const dialogRef = useRef<HTMLDialogElement | null>(null);
  const [downloading, setDownloading] = useState<boolean>(false);
  const [copiedSuccess, setCopiedSuccess] = useState<boolean>(false);

  const WATERMARK_TEXT = "Generated by Kur App (https://kur.kyrshan.com), Data Sourced from tynrai.in";

  // Sync with native <dialog> element per Modern Web Guidance
  useEffect(() => {
    const dialog = dialogRef.current;
    if (!dialog) return;

    if (isOpen) {
      if (!dialog.open) dialog.showModal();
    } else {
      if (dialog.open) dialog.close();
    }
  }, [isOpen]);

  // Click outside fallback per Modern Web Guidance
  useEffect(() => {
    const dialog = dialogRef.current;
    if (!dialog) return;

    const handleBackdropClick = (event: MouseEvent) => {
      if (event.target !== dialog) return;
      const rect = dialog.getBoundingClientRect();
      const isContent = (
        rect.top <= event.clientY &&
        event.clientY <= rect.top + rect.height &&
        rect.left <= event.clientX &&
        event.clientX <= rect.left + rect.width
      );
      if (!isContent) {
        onClose();
      }
    };

    dialog.addEventListener('click', handleBackdropClick);
    return () => dialog.removeEventListener('click', handleBackdropClick);
  }, [onClose]);

  if (!isOpen) return null;

  // Export as Image (PNG with Watermark)
  const handleExportImage = () => {
    setDownloading(true);
    try {
      if (viewMode === 'graph' && canvasRef?.current) {
        const sourceCanvas = canvasRef.current;
        const exportCanvas = document.createElement('canvas');
        const dpr = window.devicePixelRatio || 1;
        const width = sourceCanvas.width;
        const height = sourceCanvas.height + 70 * dpr;

        exportCanvas.width = width;
        exportCanvas.height = height;

        const ctx = exportCanvas.getContext('2d');
        if (!ctx) return;

        // White background
        ctx.fillStyle = '#ffffff';
        ctx.fillRect(0, 0, width, height);

        // Draw graph
        ctx.drawImage(sourceCanvas, 0, 0);

        // Watermark Banner Footer
        ctx.fillStyle = '#f8fafc';
        ctx.fillRect(0, sourceCanvas.height, width, 70 * dpr);

        ctx.strokeStyle = '#e2e8f0';
        ctx.lineWidth = 1 * dpr;
        ctx.beginPath();
        ctx.moveTo(0, sourceCanvas.height);
        ctx.lineTo(width, sourceCanvas.height);
        ctx.stroke();

        ctx.fillStyle = '#0f172a';
        ctx.font = `bold ${14 * dpr}px "Cinzel", serif`;
        ctx.textAlign = 'left';
        ctx.fillText(`Tipkur Tipkha — Ka Jait: ${query}`, 20 * dpr, sourceCanvas.height + 30 * dpr);

        ctx.fillStyle = '#64748b';
        ctx.font = `${11 * dpr}px "Plus Jakarta Sans", sans-serif`;
        ctx.fillText(WATERMARK_TEXT, 20 * dpr, sourceCanvas.height + 50 * dpr);

        // Download PNG
        const link = document.createElement('a');
        link.download = `kur-${query.toLowerCase()}-graph.png`;
        link.href = exportCanvas.toDataURL('image/png');
        link.click();
      } else {
        // Table view canvas representation
        const tableCanvas = document.createElement('canvas');
        const width = 1200;
        const rowHeight = 36;
        const nodes = graphData.nodes.filter(n => n.tier !== 'origin');
        const height = Math.max(600, 140 + nodes.length * rowHeight);

        tableCanvas.width = width;
        tableCanvas.height = height;

        const ctx = tableCanvas.getContext('2d');
        if (!ctx) return;

        ctx.fillStyle = '#ffffff';
        ctx.fillRect(0, 0, width, height);

        // Header
        ctx.fillStyle = '#0f172a';
        ctx.font = 'bold 24px "Cinzel", serif';
        ctx.fillText(`Tipkur Tipkha — Ki Kur jong ka jait ${query}`, 30, 45);

        ctx.fillStyle = '#64748b';
        ctx.font = '13px "Plus Jakarta Sans", sans-serif';
        ctx.fillText(`Total connected clans: ${nodes.length}`, 30, 75);

        // Table Header
        ctx.fillStyle = '#f1f5f9';
        ctx.fillRect(30, 95, width - 60, 32);
        ctx.fillStyle = '#334155';
        ctx.font = 'bold 12px "Plus Jakarta Sans", sans-serif';
        ctx.fillText('Jait / Surname', 45, 116);
        ctx.fillText('Kyrdan / Tier', 320, 116);
        ctx.fillText('Tyngshop / Cluster', 580, 116);

        // Rows
        ctx.font = '12px "Plus Jakarta Sans", sans-serif';
        nodes.forEach((n, idx) => {
          const y = 145 + idx * rowHeight;
          if (idx % 2 === 0) {
            ctx.fillStyle = '#f8fafc';
            ctx.fillRect(30, y - 18, width - 60, rowHeight);
          }
          ctx.fillStyle = '#0f172a';
          ctx.fillText(n.label, 45, y);
          ctx.fillStyle = '#2E8B57';
          ctx.fillText(n.tier.toUpperCase(), 320, y);
          ctx.fillStyle = '#64748b';
          ctx.fillText(n.clusterTitle || '—', 580, y);
        });

        // Watermark
        ctx.fillStyle = '#f8fafc';
        ctx.fillRect(0, height - 50, width, 50);
        ctx.fillStyle = '#64748b';
        ctx.font = '12px "Plus Jakarta Sans", sans-serif';
        ctx.fillText(WATERMARK_TEXT, 30, height - 20);

        const link = document.createElement('a');
        link.download = `kur-${query.toLowerCase()}-table.png`;
        link.href = tableCanvas.toDataURL('image/png');
        link.click();
      }

      setCopiedSuccess(true);
      setTimeout(() => setCopiedSuccess(false), 2000);
    } catch (err) {
      console.error(err);
    } finally {
      setDownloading(false);
    }
  };

  // Export as PDF / Print Preview
  const handleExportPDF = () => {
    // Open a formatted print layout in a new tab with watermark
    const printWindow = window.open('', '_blank');
    if (!printWindow) {
      window.print();
      return;
    }

    const nodes = graphData.nodes.filter(n => n.tier !== 'origin');
    const rowsHtml = nodes.map((n, idx) => `
      <tr style="border-bottom: 1px solid #e2e8f0; font-size: 13px;">
        <td style="padding: 8px 12px; color: #64748b;">${idx + 1}</td>
        <td style="padding: 8px 12px; font-weight: 700; color: #0f172a;">${n.label}</td>
        <td style="padding: 8px 12px; color: #2E8B57; font-weight: 600;">${n.tier.toUpperCase()}</td>
        <td style="padding: 8px 12px; color: #334155;">${n.clusterTitle || '—'}</td>
        <td style="padding: 8px 12px; color: #64748b;">${n.relationshipPath?.khasi || n.relationshipPath?.english || ''}</td>
      </tr>
    `).join('');

    const htmlContent = `
      <!DOCTYPE html>
      <html>
        <head>
          <title>Tipkur Tipkha - ${query}</title>
          <style>
            @page { size: A4; margin: 15mm; }
            body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; color: #0f172a; margin: 0; padding: 20px; }
            .header { border-bottom: 2px solid #2E8B57; padding-bottom: 12px; margin-bottom: 16px; }
            h1 { font-family: Georgia, serif; margin: 0 0 6px 0; color: #0f172a; }
            .meta { font-size: 13px; color: #64748b; }
            table { width: 100%; border-collapse: collapse; margin-top: 16px; }
            th { text-align: left; padding: 8px 12px; background: #f1f5f9; font-size: 11px; text-transform: uppercase; color: #475569; }
            .watermark { margin-top: 30px; padding-top: 12px; border-top: 1px solid #cbd5e1; font-size: 11px; color: #64748b; font-style: italic; text-align: center; }
          </style>
        </head>
        <body>
          <div class="header">
            <h1>Tipkur Tipkha — Ki Kur jong ka Jait: ${query}</h1>
            <div class="meta">View: ${viewMode === 'graph' ? 'Force Network Simulation' : 'Structured Clan Table'} • Date: ${new Date().toLocaleDateString()}</div>
          </div>
          <table>
            <thead>
              <tr>
                <th>#</th>
                <th>Clan Surname</th>
                <th>Tier</th>
                <th>Ancestral Cluster</th>
                <th>Relationship</th>
              </tr>
            </thead>
            <tbody>
              ${rowsHtml}
            </tbody>
          </table>
          <div class="watermark">
            ${WATERMARK_TEXT}
          </div>
          <script>
            window.onload = function() {
              window.print();
            };
          </script>
        </body>
      </html>
    `;

    printWindow.document.open();
    printWindow.document.write(htmlContent);
    printWindow.document.close();
  };

  return (
    <dialog
      ref={dialogRef}
      // MANDATORY per Modern Web Guidance: closedby="any"
      {...({ closedby: 'any' } as any)}
      aria-labelledby="share-dialog-title"
      className="m-0 sm:m-auto w-full sm:max-w-md max-h-[90vh] sm:rounded-3xl rounded-t-3xl bg-white text-slate-900 p-0 shadow-2xl border border-slate-200 backdrop:bg-slate-950/50 backdrop:backdrop-blur-xs fixed bottom-0 sm:bottom-auto inset-x-0 overflow-hidden outline-none animate-in fade-in zoom-in-95 duration-200 z-[60]"
    >
      <div className="p-6 space-y-5">
        {/* Header */}
        <div className="flex items-center justify-between pb-3 border-b border-slate-100">
          <div>
            <h3 id="share-dialog-title" className="font-serif font-bold text-lg text-slate-900">
              {language === 'kha' ? 'Sam ia kane ka View' : 'Share Current View'}
            </h3>
            <p className="text-xs text-slate-500">
              {language === 'kha' ? `Ka jait: ${query} (${viewMode === 'graph' ? 'Graph View' : 'Table View'})` : `Clan: ${query} (${viewMode.toUpperCase()} View)`}
            </p>
          </div>

          <button
            type="button"
            onClick={onClose}
            className="p-1.5 rounded-full text-slate-400 hover:text-slate-800 hover:bg-slate-100 transition cursor-pointer"
            aria-label="Close"
            autoFocus
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Options */}
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
          {/* Share as Image */}
          <button
            type="button"
            onClick={handleExportImage}
            disabled={downloading}
            className="p-4 rounded-2xl border border-slate-200 hover:border-emerald-400 hover:bg-emerald-50/50 transition text-left space-y-2 group cursor-pointer shadow-xs"
          >
            <div className="w-9 h-9 rounded-xl bg-emerald-50 text-emerald-700 flex items-center justify-center group-hover:scale-105 transition-transform">
              {copiedSuccess ? <Check className="w-5 h-5 text-emerald-600" /> : <Image className="w-5 h-5" />}
            </div>
            <div>
              <div className="font-bold text-sm text-slate-900 flex items-center gap-1.5">
                <span>{language === 'kha' ? 'Kynshew kum ka Dur' : 'Save as Image'}</span>
                <Download className="w-3.5 h-3.5 text-slate-400" />
              </div>
              <p className="text-[11px] text-slate-500 mt-0.5">
                PNG format with embedded watermark
              </p>
            </div>
          </button>

          {/* Share as PDF */}
          <button
            type="button"
            onClick={handleExportPDF}
            className="p-4 rounded-2xl border border-slate-200 hover:border-emerald-400 hover:bg-emerald-50/50 transition text-left space-y-2 group cursor-pointer shadow-xs"
          >
            <div className="w-9 h-9 rounded-xl bg-emerald-50 text-emerald-700 flex items-center justify-center group-hover:scale-105 transition-transform">
              <FileText className="w-5 h-5" />
            </div>
            <div>
              <div className="font-bold text-sm text-slate-900 flex items-center gap-1.5">
                <span>{language === 'kha' ? 'Kynshew kum ka PDF' : 'Save as PDF'}</span>
                <Printer className="w-3.5 h-3.5 text-slate-400" />
              </div>
              <p className="text-[11px] text-slate-500 mt-0.5">
                Printable document with watermark
              </p>
            </div>
          </button>
        </div>

        {/* Watermark Notice */}
        <div className="p-3 rounded-xl bg-slate-50 border border-slate-200 text-[11px] text-slate-500 italic text-center">
          Watermark: "{WATERMARK_TEXT}"
        </div>
      </div>
    </dialog>
  );
};
