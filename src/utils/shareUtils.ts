export const WATERMARK_TEXT = "Generated by Kur App (https://kur.kyrshan.com), Data Sourced from tynrai.in";

export const generateGraphBlobWithWatermark = async (
  sourceCanvas: HTMLCanvasElement,
  query: string,
  isDark: boolean
): Promise<Blob | null> => {
  const exportCanvas = document.createElement('canvas');
  const dpr = window.devicePixelRatio || 1;
  const width = sourceCanvas.width;
  const height = sourceCanvas.height + 70 * dpr;

  exportCanvas.width = width;
  exportCanvas.height = height;

  const ctx = exportCanvas.getContext('2d');
  if (!ctx) return null;

  // Background matching active theme
  ctx.fillStyle = isDark ? '#090e0c' : '#ffffff';
  ctx.fillRect(0, 0, width, height);

  // Draw graph
  ctx.drawImage(sourceCanvas, 0, 0);

  // Watermark Banner Footer
  ctx.fillStyle = isDark ? '#111a16' : '#f8fafc';
  ctx.fillRect(0, sourceCanvas.height, width, 70 * dpr);

  ctx.strokeStyle = isDark ? '#1f352c' : '#e2e8f0';
  ctx.lineWidth = 1 * dpr;
  ctx.beginPath();
  ctx.moveTo(0, sourceCanvas.height);
  ctx.lineTo(width, sourceCanvas.height);
  ctx.stroke();

  ctx.fillStyle = isDark ? '#f8fafc' : '#0f172a';
  ctx.font = `bold ${14 * dpr}px "Playfair Display", Georgia, serif`;
  ctx.textAlign = 'left';
  ctx.fillText(`Tipkur Tipkha — Ka Jait: ${query}`, 20 * dpr, sourceCanvas.height + 30 * dpr);

  ctx.fillStyle = isDark ? '#94a3b8' : '#64748b';
  ctx.font = `${11 * dpr}px "Plus Jakarta Sans", sans-serif`;
  ctx.fillText(WATERMARK_TEXT, 20 * dpr, sourceCanvas.height + 50 * dpr);

  return new Promise((resolve) => {
    exportCanvas.toBlob((blob) => resolve(blob), 'image/png');
  });
};

export const shareToWhatsApp = async (
  sourceCanvas: HTMLCanvasElement | null,
  query: string,
  isDark: boolean
) => {
  const shareText = `Tipkur Tipkha — Ki kur jong ka jait ${query}.\nData Sourced from tynrai.in: https://kur.kyrshan.com`;

  if (sourceCanvas) {
    try {
      const blob = await generateGraphBlobWithWatermark(sourceCanvas, query, isDark);
      if (blob) {
        const file = new File([blob], `kur-${query.toLowerCase()}-graph.png`, { type: 'image/png' });

        // If Web Share API supports file sharing (Mobile Chrome/Safari/WhatsApp share sheet)
        if (navigator.canShare && navigator.canShare({ files: [file] })) {
          try {
            await navigator.share({
              files: [file],
              title: `Tipkur Tipkha — ${query}`,
              text: shareText
            });
            return;
          } catch (err: any) {
            if (err.name === 'AbortError') return;
          }
        }

        // Fallback for browsers that cannot share files directly:
        // Automatically download the graph PNG image with watermark
        const link = document.createElement('a');
        link.download = `kur-${query.toLowerCase()}-graph.png`;
        link.href = URL.createObjectURL(blob);
        link.click();
        setTimeout(() => URL.revokeObjectURL(link.href), 10000);
      }
    } catch (err) {
      console.error('Error generating graph blob for WhatsApp share:', err);
    }
  }

  // Open WhatsApp with pre-filled message
  const whatsappUrl = `https://api.whatsapp.com/send?text=${encodeURIComponent(shareText)}`;
  window.open(whatsappUrl, '_blank', 'noopener,noreferrer');
};
